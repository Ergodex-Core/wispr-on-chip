"""Emit src/main/scala/minicpm/generated/WeightTables.scala from weights/MANIFEST.json.

Each tensor becomes a WeightTensor entry (name, kind, width, depth, file, sha256, base address in its
address space). The Scala side reads the weight images at elaboration time (WeightStore.scala).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from gen.chipmap import REPO, SPACE_OF, tensor_bases  # noqa: E402

OUT = REPO / "src/main/scala/minicpm/generated/WeightTables.scala"


def main():
    man = json.load(open(REPO / "weights" / "MANIFEST.json"))
    T = man["tensors"]
    B = tensor_bases(man)
    entries = []
    totals = {"w": 0, "p": 0, "t": 0}
    for name in sorted(T):
        t = T[name]
        shape = ", ".join(str(x) for x in t["shape"])
        totals[SPACE_OF[t["kind"]]] = max(totals[SPACE_OF[t["kind"]]], B[name] + t["depth"])
        entries.append(f'    WeightTensor("{name}", "{t["kind"]}", {t["width_bits"]}, {t["depth"]}, {B[name]}, '
                       f'"{t["file"]}", "{t["sha256"]}", Seq({shape}))')
    src = "// GENERATED by gen/emit_weights.py from weights/MANIFEST.json — do not edit.\n"
    src += "package minicpm.generated\n\nimport minicpm.WeightTensor\n\n"
    src += "object WeightTables {\n"
    src += f'  val CheckpointSha256 = "{man["checkpoint_sha256"]}"\n'
    src += f"  val WSpaceWords = {totals['w']}\n  val PSpaceWords = {totals['p']}\n  val TSpaceWords = {totals['t']}\n"
    src += "  val tensors: Seq[WeightTensor] = Seq(\n" + ",\n".join(entries) + "\n  )\n"
    src += "  val byName: Map[String, WeightTensor] = tensors.map(t => t.name -> t).toMap\n"
    src += "}\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(src)
    print(f"wrote {OUT} ({len(entries)} tensors; space words {totals})")


if __name__ == "__main__":
    main()
