"""Emit src/main/scala/whisper/generated/WeightTables.scala from weights/MANIFEST.json.

Each tensor becomes a WeightTensor entry (name, kind, width, depth, file, sha256, base address in its
address space). The Scala side reads the committed hex files at elaboration time (see WeightStore.scala).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from golden.data import REPO  # noqa: E402

OUT = REPO / "src/main/scala/whisper/generated/WeightTables.scala"
SPACES = {"w8": 2048, "i32vec": 1024, "i8mat": 256}


def main():
    man = json.load(open(REPO / "weights" / "MANIFEST.json"))
    T = man["tensors"]
    bases = {k: 0 for k in SPACES}
    entries = []
    for name in sorted(T):
        t = T[name]
        base = bases[t["kind"]]
        bases[t["kind"]] += t["depth"]
        shape = ", ".join(str(x) for x in t["shape"])
        entries.append(f'    WeightTensor("{name}", "{t["kind"]}", {t["width_bits"]}, {t["depth"]}, {base}, '
                       f'"{t["file"]}", "{t["sha256"]}", Seq({shape}))')
    src = "// GENERATED by gen/emit_weights.py from weights/MANIFEST.json — do not edit.\n"
    src += "package whisper.generated\n\nimport whisper.WeightTensor\n\n"
    src += "object WeightTables {\n"
    src += f'  val CheckpointSha256 = "{man["checkpoint_sha256"]}"\n'
    for k, v in bases.items():
        src += f"  val {k.capitalize()}SpaceWords = {v}\n"
    src += "  val tensors: Seq[WeightTensor] = Seq(\n" + ",\n".join(entries) + "\n  )\n"
    src += "  val byName: Map[String, WeightTensor] = tensors.map(t => t.name -> t).toMap\n"
    src += "}\n"
    OUT.write_text(src)
    print(f"wrote {OUT} ({len(entries)} tensors; spaces {bases})")


if __name__ == "__main__":
    main()
