"""Emit every LUT from golden/luts.py + quant.py into src/main/scala/whisper/generated/Luts.scala."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from golden import luts  # noqa: E402
from golden.data import REPO  # noqa: E402
from golden.quant import phi_table  # noqa: E402

OUT = REPO / "src/main/scala/whisper/generated/Luts.scala"


def seq(name: str, vals: list[int], width: int) -> str:
    rows = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    body = ",\n    ".join(rows)
    return f"  /** {len(vals)} entries, {width}-bit */\n  val {name}: Seq[Int] = Seq(\n    {body}\n  )\n"


def main():
    exp = luts.exp_table()
    rsq = luts.rsqrt_table()
    phi = phi_table()
    src = "// GENERATED by gen/emit_luts.py from golden/luts.py — do not edit.\n"
    src += "package whisper.generated\n\n"
    src += "object Luts {\n"
    src += f"  val ExpDBits = {luts.EXP_D_BITS}\n  val ExpInterpBits = {luts.EXP_INTERP_BITS}\n  val ExpOne = {luts.EXP_OUT_ONE}\n"
    src += f"  val RsqrtIdxShift = {luts.RSQRT_IDX_SHIFT}\n  val RsqrtYShift = {luts.RSQRT_Y_SHIFT}\n"
    src += seq("Exp", exp, 16)        # T[0..255]; T[256] = 0 implicit
    src += seq("Rsqrt", rsq, 17)
    src += seq("Phi", phi, 16)        # PHI[0..255]; PHI[256] = 32768 implicit
    src += "}\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(src)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
